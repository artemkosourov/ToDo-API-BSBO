def calculate_quadrant(is_important: bool, is_urgent: bool) -> str:
    """Вычисляет квадрант матрицы Эйзенхауэра"""
    if is_important and is_urgent:
        return "Q1"
    elif is_important and not is_urgent:
        return "Q2"
    elif not is_important and is_urgent:
        return "Q3"
    else:
        return "Q4"